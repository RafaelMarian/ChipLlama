"""Export generated code as a folder ready for MPLAB X IDE (+ build.bat / Makefile fallbacks)."""
from __future__ import annotations

import re
from pathlib import Path

BUILD_BAT = """@echo off
REM Build with MPLAB XC16 from the command line. Edit XC16_BIN to match your install.
set XC16_BIN=C:\\Program Files\\Microchip\\xc16\\v2.10\\bin
"%XC16_BIN%\\xc16-gcc.exe" -mcpu={mcpu} -O1 -Wall main.c -o main.elf || exit /b 1
"%XC16_BIN%\\xc16-bin2hex.exe" main.elf || exit /b 1
echo Built main.hex
"""

MAKEFILE = """XC16 ?= xc16-gcc
BIN2HEX ?= xc16-bin2hex
MCPU = {mcpu}
main.hex: main.elf
\t$(BIN2HEX) main.elf
main.elf: main.c
\t$(XC16) -mcpu=$(MCPU) -O1 -Wall main.c -o main.elf
clean:
\trm -f main.elf main.hex main.o
"""

INSTRUCTIONS = """# Open in MPLAB X IDE

Generated by ChipLlama for **{device}** (XC16, PICkit 5).

## Option A - use the code in your own MPLAB X project (recommended)
1. File -> New Project -> Microchip Embedded -> Standalone Project.
2. Family: 16-bit MCUs (PIC24/dsPIC)   Device: {device}.
3. Tool: PICkit 5 (select the serial number shown).   Compiler: XC16.
4. Finish, then right-click *Source Files* -> Add Existing Item... -> `main.c` from this folder
   (or paste the init function into your own main.c).
5. Set the oscillator / configuration bits in your project (Window -> Target Memory Views -> Configuration Bits,
   or `#pragma config` / `_CONFIGx()` macros). ChipLlama does not generate configuration bits.
6. Production -> Make and Program Device (the green PICkit icon) - or Debug if you want to single-step.

## Option B - command line
* Windows: edit `XC16_BIN` in `build.bat`, run it -> `main.hex`; program with MPLAB X or IPE.
* Optional CLI programming with IPE (off by default in ChipLlama):
  `ipecmd.exe -P{part} -TPPK5 -Fmain.hex -M -Y -OL`

Clock assumption used for the checker: Fosc = {fosc_mhz:g} MHz -> Fcy = Fosc/2 = {fcy_mhz:g} MHz.
Timer reference solution: {summary}
"""


def export_project(code: str, out_dir: str | Path, device: str = "PIC24FJ256GB110", spec=None, solution=None) -> list[Path]:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    mcpu = device.upper().replace("PIC", "")
    part = mcpu
    fosc = spec.fosc_hz / 1e6 if spec else 32.0
    summary = "n/a"
    if solution is not None:
        summary = (f"Timer{solution.spec.timer} TCKPS={solution.tckps} (1:{solution.prescale}), PR={solution.period_reg}, "
                   f"period {solution.achieved_s*1e3:.6g} ms ({solution.error_ppm:+.0f} ppm)")
    files = {
        "main.c": code if code.endswith("\n") else code + "\n",
        "build.bat": BUILD_BAT.format(mcpu=mcpu).replace("\n", "\r\n"),
        "Makefile": MAKEFILE.format(mcpu=mcpu),
        "OPEN_IN_MPLABX.md": INSTRUCTIONS.format(device=device, part=part, fosc_mhz=fosc, fcy_mhz=fosc / 2, summary=summary),
    }
    paths = []
    for name, text in files.items():
        p = out / name
        with open(p, "w", encoding="utf-8", newline="") as f:
            f.write(text)
        paths.append(p)
    return paths
