"""Makefile / linker / startup / README for family projects."""
from __future__ import annotations

from pathlib import Path

from . import FQBN

AVR_MCU = {"ATMEGA328P": "atmega328p", "ATMEGA2560": "atmega2560"}
AVRDUDE = {"ATMEGA328P": "-c arduino -p m328p -b 115200", "ATMEGA2560": "-c wiring -p m2560 -b 115200 -D"}


def _srcs(p):
    return " \\\n       ".join(sorted(k for k in p.files if k.endswith(".c")))


def avr_makefile(p) -> str:
    mcu = AVR_MCU[p.b["mcu"]]
    return f"""# {p.b['title']} ({p.b['mcu']}) - avr-gcc bare-metal build. Generated by ChipLlama.
# make          -> build/app.hex
# make flash PORT=COM5   (needs avrdude; never run automatically)
MCU    = {mcu}
F_CPU  = {int(p.fcy)}UL
CC     = avr-gcc
OBJCOPY= avr-objcopy
SIZE   = avr-size
CFLAGS = -mmcu=$(MCU) -DF_CPU=$(F_CPU) -Os -std=c99 -Wall -Wextra -ffunction-sections -fdata-sections -Ihal -Iboard -Idrivers -Iapp
LDFLAGS= -mmcu=$(MCU) -Wl,--gc-sections
SRCS   = {_srcs(p)}
OBJS   = $(SRCS:%.c=build/%.o)

all: build/app.hex

build/%.o: %.c
\t@mkdir -p $(dir $@)
\t$(CC) $(CFLAGS) -c $< -o $@

build/app.elf: $(OBJS)
\t$(CC) $(LDFLAGS) $^ -o $@
\t$(SIZE) $@

build/app.hex: build/app.elf
\t$(OBJCOPY) -O ihex -R .eeprom $< $@

flash: build/app.hex
\tavrdude {AVRDUDE[p.b['mcu']]} -P $(PORT) -U flash:w:build/app.hex:i

clean:
\trm -rf build

.PHONY: all clean flash
"""


def stm_makefile(p) -> str:
    from .project import STM
    cpu = STM[p.series]["cpu"]
    return f"""# {p.b['title']} ({p.b['mcu']}) - arm-none-eabi-gcc bare-metal build (CMSIS headers, own HAL). Generated by ChipLlama.
# make          -> build/app.hex / app.bin
# make flash    (st-flash or STM32_Programmer_CLI; never run automatically)
PREFIX = arm-none-eabi-
CC     = $(PREFIX)gcc
OBJCOPY= $(PREFIX)objcopy
SIZE   = $(PREFIX)size
ARCH   = -mcpu={cpu} -mthumb -mfloat-abi=soft
CFLAGS = $(ARCH) -D{p.sd['define']} -Os -g -std=c99 -Wall -Wextra -ffunction-sections -fdata-sections \\
         -Icmsis -Ihal -Iboard -Idrivers -Iapp
LDFLAGS= $(ARCH) -T{p.b['mcu'].lower()}.ld --specs=nano.specs --specs=nosys.specs -Wl,--gc-sections -Wl,-Map=build/app.map
SRCS   = {_srcs(p)}
ASRCS  = cmsis/{p.sd['startup']}
OBJS   = $(SRCS:%.c=build/%.o) $(ASRCS:%.s=build/%.o)

all: build/app.hex build/app.bin

build/%.o: %.c
\t@mkdir -p $(dir $@)
\t$(CC) $(CFLAGS) -c $< -o $@

build/%.o: %.s
\t@mkdir -p $(dir $@)
\t$(CC) $(ARCH) -c $< -o $@

build/app.elf: $(OBJS)
\t$(CC) $(LDFLAGS) $^ -o $@
\t$(SIZE) $@

build/app.hex: build/app.elf
\t$(OBJCOPY) -O ihex $< $@

build/app.bin: build/app.elf
\t$(OBJCOPY) -O binary $< $@

flash: build/app.bin
\tst-flash write build/app.bin 0x08000000

clean:
\trm -rf build

.PHONY: all clean flash
"""


def stm_files(p) -> dict:
    from .stm32 import LINKER
    from .project import CMSIS
    out = {f"{p.b['mcu'].lower()}.ld": LINKER.format(mcu=p.b["mcu"], flash=p.sd["flash_k"], ram=p.sd["ram_k"])}
    hdr = p.sd["header"]
    fam = {"f1": "stm32f1xx.h", "f4": "stm32f4xx.h", "f0": "stm32f0xx.h"}[p.series]
    core = {"f1": "core_cm3.h", "f4": "core_cm4.h", "f0": "core_cm0.h"}[p.series]
    need = [hdr, fam, f"system_{fam}", core, "cmsis_compiler.h", "cmsis_gcc.h", "cmsis_version.h", p.sd["startup"]]
    if p.series == "f4":
        need.append("mpu_armv7.h")
    need += [x.name for x in CMSIS.glob("LICENSE*")]
    for n in need:
        f = CMSIS / n
        if f.exists():
            out[f"cmsis/{n}"] = f.read_text(errors="replace")
    return out


def readme(p) -> str:
    parts = "\n".join(f"| `{cid}` | {drv} | `{t}` |" for cid, drv, t, *_ in p.inst)
    notes = "\n".join(f"- {n}" for n in dict.fromkeys(p.notes)) or "- none"
    fq = FQBN.get(p.device, "")
    if p.ard:
        build = (f"- Arduino IDE: open `{p.name}/{p.name}.ino`, select the board, Verify / Upload.\n"
                 f"- arduino-cli: `arduino-cli compile --fqbn {fq} {p.name}`\n"
                 f"- The application is plain C in `{p.name}/src/` (HAL, drivers, board, main as `cl_app_main()`); "
                 "`src/hal_arduino.cpp` implements the HAL on the Arduino core.")
    elif p.family == "avr":
        build = ("- `make` with avr-gcc on PATH (Arduino IDE ships it in `hardware/tools/avr/bin`, or `arduino-cli core install arduino:avr`).\n"
                 f"- Upload: `make flash PORT=COM5` (avrdude, bootloader) - never done automatically.")
    else:
        build = ("- `make` with the Arm GNU toolchain (`arm-none-eabi-gcc`) on PATH - STM32CubeIDE ships one in "
                 "`plugins/*gnu-tools-for-stm32*/tools/bin`.\n"
                 "- `cmsis/` holds the ST CMSIS device header + startup file (Apache-2.0), the linker script is ours.\n"
                 "- Flash: `make flash` (st-flash) or STM32CubeProgrammer - never done automatically.")
    return f"""# {p.name} - {p.b['title']} ({p.b['mcu']})

Generated by ChipLlama from the Circuit tab (deterministic generator, no AI). Family: **{p.family.upper()}**, mode: **{p.mode}**.
Clock: {p.clock_desc}.

## Layout

| folder | contents |
|---|---|
| `hal/` | `hal.h`, `hal_config.h` (every computed constant), gpio/timer/uart/i2c/spi/adc/pwm |
| `drivers/` | one driver per component kind, written only against the HAL (same drivers as the PIC projects) |
| `board/` | pin map, one `const` instance per component, `board_init()` |
| `app/main.c` | demo application |

## Components

| instance | driver | type |
|---|---|---|
{parts}

## Build

{build}

## Notes

{notes}
"""


def family_build_files(p):
    if p.ard:
        p.files["README.md"] = readme(p)
        return
    if p.family == "avr":
        p.files["Makefile"] = avr_makefile(p)
    else:
        p.files.update(stm_files(p))
        p.files["Makefile"] = stm_makefile(p)
    p.files["README.md"] = readme(p)
