"""Makefile, MPLAB X nbproject and README for a generated project."""
from __future__ import annotations

from ..edc import compiler_cpu

TOOL = {"xc8": ("xc8-cc", "XC8"), "xc16": ("xc16-gcc", "XC16"), "xc32": ("xc32-gcc", "XC32")}


def _srcs(p):
    return sorted(f for f in p.files if f.endswith(".c"))


def makefile(p) -> str:
    cc, _ = TOOL[p.comp]
    cpu = compiler_cpu(p.device)
    srcs = " \\\n       ".join(_srcs(p))
    inc = "-Ihal -Idrivers -Iboard -Iconfig"
    if p.comp == "xc16":
        link = (f"$(CC) -mcpu=$(CPU) -omf=elf $(OBJS) -o $@ -Wl,--script=p$(CPU).gld,--heap=0,--stack=16,--check-sections,"
                "--data-init,--pack-data,--handles,--isr,--no-gc-sections,--fill-upper=0,--stackguard=16,--no-force-link,--smart-io")
        rules = f"""CC   ?= xc16-gcc
CPU   = {cpu}
CFLAGS = -mcpu=$(CPU) -omf=elf -O1 -Wall {inc}
OBJS  = $(SRCS:%.c=build/%.o)

all: build/app.hex

build/%.o: %.c
\t@mkdir -p $(dir $@)
\t$(CC) $(CFLAGS) -c $< -o $@

build/app.elf: $(OBJS)
\t{link}

build/app.hex: build/app.elf
\txc16-bin2hex $<
"""
    elif p.comp == "xc8":
        rules = f"""CC   ?= xc8-cc
CPU   = {cpu}
CFLAGS = -mcpu=$(CPU) -O1 {inc}

all: build/app.hex

build/app.hex: $(SRCS)
\t@mkdir -p build
\t$(CC) $(CFLAGS) $(SRCS) -o $@
"""
    else:
        rules = f"""CC   ?= xc32-gcc
CPU   = {cpu}
CFLAGS = -mprocessor=$(CPU) -O1 -Wall {inc}

all: build/app.hex

build/app.elf: $(SRCS)
\t@mkdir -p build
\t$(CC) $(CFLAGS) $(SRCS) -o $@

build/app.hex: build/app.elf
\txc32-bin2hex $<
"""
    return f"""# Generated by ChipLlama for {p.device} ({p.comp.upper()}).
# Usage: make            (compiler on PATH)   |   make CC="C:/Program Files/Microchip/{p.comp}/vX.YY/bin/{cc}.exe"
SRCS = {srcs}

{rules}
clean:
\trm -rf build

.PHONY: all clean
"""


def nbproject(p) -> dict:
    cc, tc = TOOL[p.comp]
    name = getattr(p, "name", None) or "chipllama_circuit"
    groups = {}
    for f in sorted(p.files):
        if f.endswith((".c", ".h")) and "/" in f:
            groups.setdefault(f.split("/")[0], []).append(f)
    lf = "\n".join(f'    <logicalFolder name="{g}" displayName="{g}" projectFiles="true">\n'
                   + "\n".join(f"      <itemPath>{f}</itemPath>" for f in fs) + "\n    </logicalFolder>" for g, fs in groups.items())
    conf = f"""<?xml version="1.0" encoding="UTF-8"?>
<configurationDescriptor version="65">
  <logicalFolder name="root" displayName="root" projectFiles="true">
{lf}
  </logicalFolder>
  <sourceRootList>
    <Elem>.</Elem>
  </sourceRootList>
  <projectmakefile>Makefile</projectmakefile>
  <confs>
    <conf name="default" type="2">
      <toolsSet>
        <developmentServer>localhost</developmentServer>
        <targetDevice>{p.device}</targetDevice>
        <targetHeader></targetHeader>
        <platformTool>noID</platformTool>
        <languageToolchain>{tc}</languageToolchain>
        <platform>2</platform>
      </toolsSet>
      <compileType>
        <linkerTool><linkerLibItems></linkerLibItems></linkerTool>
        <loading><useAlternateLoadableFile>false</useAlternateLoadableFile></loading>
      </compileType>
      <{p.comp}-config>
        <property key="extra-include-directories" value="hal;drivers;board;config"/>
        <property key="optimization-level" value="-O1"/>
      </{p.comp}-config>
    </conf>
  </confs>
</configurationDescriptor>
"""
    proj = f"""<?xml version="1.0" encoding="UTF-8"?>
<project xmlns="http://www.netbeans.org/ns/project/1">
  <type>com.microchip.mplab.nbide.embedded.makeproject</type>
  <configuration>
    <data xmlns="http://www.netbeans.org/ns/make-project/1">
      <name>{name}</name>
      <creation-uuid>00000000-0000-0000-0000-000000000000</creation-uuid>
      <make-project-type>0</make-project-type>
      <c-extensions>c</c-extensions>
      <cpp-extensions/>
      <header-extensions>h</header-extensions>
      <sourceEncoding>UTF-8</sourceEncoding>
      <make-dep-projects/>
    </data>
  </configuration>
</project>
"""
    return {"nbproject/configurations.xml": conf, "nbproject/project.xml": proj}


def readme(p) -> str:
    cc, tc = TOOL[p.comp]
    parts = "\n".join(f"| `{cid}` | {drv} | `{t}` |" for cid, drv, t, *_ in p.inst)
    notes = "\n".join(f"- {n}" for n in dict.fromkeys(p.notes)) or "- none"
    return f"""# {getattr(p, 'name', 'chipllama_circuit')} - {p.device}

Generated by ChipLlama from the Circuit tab (deterministic generator, no AI). Toolchain: **{tc}** (`{cc}`).
Clock: {p.clock_desc}. Back end: `{p.kind}`.

## Layout

| folder | contents |
|---|---|
| `config/` | configuration bits from Microchip EDC data |
| `hal/` | `hal.h` status codes, `hal_config.h` every computed register constant, gpio/timer/uart/i2c/spi/adc/pwm |
| `drivers/` | one driver per component kind, written only against the HAL |
| `board/` | pin map, one `const` instance per component, `board_init()` |
| `app/main.c` | demo application |

## Components

| instance | driver | type |
|---|---|---|
{parts}

## Build

- MPLAB X: *File > Open Project* on this folder (`nbproject/`), select the {tc} toolchain, Build.
- Command line: `make` (with `{cc}` on PATH). Output: `build/app.hex`.
- Programming is never done automatically.

## Notes

{notes}
"""
