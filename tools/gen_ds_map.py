"""Generate chipllama/ds_map_tables.py from the DS39897C SFR map (pdftotext -layout text).

    pdftotext -layout DS39897C.pdf ds.txt && python tools/gen_ds_map.py ds.txt

Covers the batch-2 peripherals (SPI, I2C, UART2-4, PMP, RTCC, CRC, RCON, PADCFG1, PMD).
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

PAGES = {"SPI?STAT": 184, "SPI?CON1": 186, "SPI?CON2": 187, "I2C?CON": 194, "I2C?STAT": 196, "U?MODE": 202,
         "U?STA": 204, "PMCON": 242, "PMMODE": 244, "PMADDR": 245, "PMAEN": 245, "PMSTAT": 246, "PADCFG1": 247,
         "RCFGCAL": 253, "ALCFGRPT": 255, "CRCCON": 265, "CRCXOR": 266, "RCON": 72}
WANT = re.compile(r"^(SPI[123](STAT|CON1|CON2|BUF)|I2C[123](RCV|TRN|BRG|CON|STAT|ADD|MSK)|U[234](MODE|STA|TXREG|RXREG|BRG)"
                  r"|U1(TXREG|RXREG)|RCFGCAL|ALCFGRPT|RTCVAL|ALRMVAL|CRCCON|CRCXOR|CRCDAT|CRCWDAT|PMCON|PMMODE|PMADDR"
                  r"|PMAEN|PMSTAT|PMDIN1|PMDOUT2|PMDIN2|RCON|PADCFG1|PMD[1-6])$")


def page(n):
    return PAGES.get(n) or PAGES.get(re.sub(r"^(SPI|I2C|U)\d", r"\1?", n)) or 0


def main(path):
    sfrs, data = {}, {}
    for line in Path(path).read_text(errors="replace").splitlines():
        t = line.split()
        if len(t) < 3 or not WANT.match(t[0]) or not re.fullmatch(r"[0-9A-F]{4}", t[1]) or t[0] in sfrs or t[0] in data:
            continue
        name, addr = t[0], int(t[1], 16)
        rst = t[-1] if re.fullmatch(r"[0-9A-Fx]{4}", t[-1]) else "0000"
        rst = int(rst.replace("x", "0"), 16)
        bits = t[2:-1] if len(t) == 19 or (len(t) == 21 and t[-2] == "Note") else None
        if len(t) >= 20 and t[-2] == "Note":
            bits, rst = t[2:18], 0
        if bits and len(bits) == 16 and not any(b.lower() in ("register", "rate") for b in bits):
            fl, i = [], 0
            bits = [b.replace("/", "_") for b in bits]
            while i < 16:
                b = bits[i]
                if b == "—":
                    i += 1
                    continue
                m = re.fullmatch(r"(.*?[A-Z_])(\d+)", b)
                if m and not b.startswith("X"):
                    base, hi = m.group(1), int(m.group(2))
                    j = i
                    while j + 1 < 16 and re.fullmatch(rf"{re.escape(base)}(\d+)", bits[j + 1]) and \
                            int(bits[j + 1][len(base):]) == int(bits[j][len(base):]) - 1:
                        j += 1
                    if j > i:
                        fl.append((base, 15 - j, j - i + 1))
                        i = j + 1
                        continue
                fl.append((b, 15 - i, 1))
                i += 1
            sfrs[name] = (name, addr, page(name), tuple(sorted(fl, key=lambda f: f[1])), rst)
        else:
            data[name] = (name, addr, rst)
    data.setdefault("PMDOUT1", ("PMDOUT1", 0x0604, 0))
    out = ['"""GENERATED by tools/gen_ds_map.py from the DS39897C SFR map - do not edit."""', "", "SFRS = ["]
    out += [f"    {v!r}," for v in sfrs.values()] + ["]", "", "DATA = ["] + [f"    {v!r}," for v in data.values()] + ["]", ""]
    Path(__file__).resolve().parents[1].joinpath("chipllama/ds_map_tables.py").write_text("\n".join(out))
    print(len(sfrs), "sfrs", len(data), "data")


if __name__ == "__main__":
    main(sys.argv[1])
