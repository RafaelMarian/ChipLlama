"""Generate chipllama/gb110_tables.py from the Microchip EDC file for PIC24FJ256GB110.

    python tools/gen_gb110_tables.py path/to/PIC24FJ256GB110.PIC

Register addresses, bit positions, POR values, interrupt vectors and pin multiplexing
come from the EDC (PIC24F-GA-GB_DFP). Page numbers are DS39897C pages, located by
searching the datasheet text for "REGISTER x-y: <name>" (filled in by hand below).
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from chipllama import edc  # noqa: E402

PAGE = {"INTCON1": 82, "INTCON2": 83,
        **{f"IFS{i}": 84 + i for i in range(6)},
        "IEC0": 90, "IEC1": 91, "IEC2": 93, "IEC3": 94, "IEC4": 95, "IEC5": 96,
        **{f"IPC{i}": 97 + i for i in range(14)}, "IPC15": 111, "IPC16": 112, "IPC18": 113, "IPC19": 113,
        "IPC20": 114, "IPC21": 115, "IPC22": 116, "IPC23": 117,
        "RPINR0": 141, "RPINR1": 141, "RPINR2": 142, "RPINR3": 142, "RPINR4": 143, "RPINR7": 143,
        "RPINR8": 144, "RPINR9": 144, "RPINR10": 145, "RPINR11": 145, "RPINR15": 146, "RPINR17": 146,
        "RPINR19": 147, "RPINR20": 148, "RPINR21": 148, "RPINR22": 149, "RPINR23": 149,
        "RPINR27": 150, "RPINR28": 150, "RPINR29": 151,
        "T4CON": 166, "T5CON": 167, "AD1CON1": 269, "AD1CON2": 270, "AD1CON3": 271, "AD1CHS": 272,
        "AD1PCFGH": 273, "AD1CSSL": 274}
for i in range(1, 10):
    PAGE[f"IC{i}CON1"], PAGE[f"IC{i}CON2"] = 171, 172
    PAGE[f"OC{i}CON1"], PAGE[f"OC{i}CON2"] = 178, 179
for p in "ABCDEFG":
    PAGE[f"PORT{p}"] = PAGE[f"LAT{p}"] = 133
    PAGE[f"ODC{p}"] = 134
for i in range(1, 7):
    PAGE[f"CNEN{i}"] = PAGE[f"CNPU{i}"] = PAGE[f"CNPD{i}"] = 135

WANT = re.compile(r"^(INTCON[12]|IFS\d|IEC\d|IPC\d+|RPINR\d+|T[45]CON|AD1CON[123]|AD1CHS|AD1PCFGH|AD1CSSL|"
                  r"IC\dCON[12]|OC\dCON[12]|(PORT|LAT|ODC|TRIS)[A-G]|CN(EN|PU|PD)\d)$")
DATA = re.compile(r"^(TMR[45]|PR[45]|TMR[35]HLD|OC\d(R|RS|TMR)|IC\d(BUF|TMR)|ADC1BUF[0-9A-F])$")
# POR values the datasheet states differently from the pack (datasheet wins, p.172/p.179)
RESET_OVERRIDE = {**{f"OC{i}CON2": 0x000C for i in range(1, 10)}, **{f"IC{i}CON2": 0x000D for i in range(1, 10)}}


def _reset(s: str) -> int:
    s = (s or "").strip()
    return int("".join("1" if c == "1" else "0" for c in s), 2) if s else 0


def main(path: str) -> None:
    dev = edc.parse_edc(path)
    x = Path(path).read_text(errors="replace")
    sfrs, data = [], []
    for n, s in sorted(dev.sfrs.items(), key=lambda kv: kv[1].address):
        if WANT.match(n) and s.fields:
            multi = {f.name for f in s.fields if f.width > 1}
            flds = [(f.name, f.lsb, f.width) for f in s.fields
                    if not (f.width == 1 and re.fullmatch(r"(.+?)\d", f.name) and re.fullmatch(r"(.+?)\d", f.name).group(1) in multi)]
            sfrs.append((n, s.address, PAGE.get(n, 0), tuple(flds), RESET_OVERRIDE.get(n, _reset(s.reset))))
        elif DATA.match(n):
            data.append((n, s.address, _reset(s.reset)))
    vectors = {m.group(1): int(m.group(2)) for m in re.finditer(r'<edc:Interrupt edc:cname="(\w+)"[^>]*edc:irq="(\d+)"', x)}
    cn, rpi = {}, {}
    for p in re.findall(r"<edc:Pin>(.*?)</edc:Pin>", x, re.S):
        names = re.findall(r'edc:name="([^"]+)"', p)
        port = [n for n in names if re.fullmatch(r"R[A-G]\d+", n)]
        if not port:
            continue
        for n in names:
            if m := re.fullmatch(r"CN(\d+)", n):
                cn[port[0]] = int(m.group(1))
            if m := re.fullmatch(r"RPI(\d+)", n):
                rpi[int(m.group(1))] = port[0]
    out = ['"""GENERATED by tools/gen_gb110_tables.py from the PIC24FJ256GB110 EDC (device pack) - do not edit.',
           "", "Addresses, bit positions, POR values, interrupt vectors and pin multiplexing are the pack's;",
           'page numbers are DS39897C pages."""', "",
           "# (name, address, datasheet page, ((field, lsb, width), ...), POR value)", "SFRS = ["]
    out += [f"    {s!r}," for s in sfrs] + ["]", "", "# 16-bit data registers: (name, address, POR value)", "DATA = ["]
    out += [f"    {d!r}," for d in data] + ["]", "",
                                          "# XC16 vector names (without the leading underscore) -> IRQ number (Table 7-2, p.79-80)",
                                          f"VECTORS = {vectors!r}", "", "# port pin -> CNn input (Change Notification)",
                                          f"CN_PIN = {cn!r}", "", "# RPIn (input-only remappable) -> port pin", f"RPI_PIN = {rpi!r}", ""]
    dst = Path(__file__).resolve().parents[1] / "chipllama" / "gb110_tables.py"
    dst.write_text("\n".join(out))
    print(f"wrote {dst}: {len(sfrs)} SFRs, {len(data)} data regs, {len(vectors)} vectors, {len(cn)} CN pins")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "PIC24FJ256GB110.PIC")
